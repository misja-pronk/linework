// Builds the viewer script that goes into every exported page: src/viewer/main.ts bundled and
// minified into src/generated/viewer.ts, as a string, so Node and the editor carry the same bytes.
// Run after changing the viewer: node packages/html-export/build.mjs (a test checks it is current).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
export const generated = path.join(here, 'src/generated/viewer.ts');

/** The viewer as the module text of src/generated/viewer.ts. */
export async function viewerModule() {
  const r = await build({ entryPoints: [path.join(here, 'src/viewer/main.ts')], bundle: true, format: 'iife', target: 'es2020', minify: true, legalComments: 'none', write: false, logLevel: 'warning', absWorkingDir: here });
  // Inline in a <script>: nothing in it may close the element or open a comment.
  const code = r.outputFiles[0].text.trim().replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
  return `// Generated by packages/html-export/build.mjs from src/viewer/main.ts: do not edit.\nexport const viewerScript = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await viewerModule();
  fs.mkdirSync(path.dirname(generated), { recursive: true });
  fs.writeFileSync(generated, text);
  console.log(`${path.relative(process.cwd(), generated)} ${(text.length / 1024).toFixed(1)} kB`);
}
