// Generates the font assets the theme package ships with.
// Inter comes from the inter-ui package (OFL-1.1):
// - fonts/Inter-<Weight>.ttf        for PNG rendering with resvg (it cannot read woff2)
// - src/generated/fonts.ts           latin-subset woff2 as base64, embedded in exported SVGs
// - src/generated/metrics.json       glyph advances + ASCII kerning, so text is measured the
//                                    same in Node and the browser without loading a font parser
// The other families are checked in as the upstream TTF files (fonts/, each with its OFL text):
// Instrument Sans (github.com/Instrument/instrument-sans), Geist Mono (github.com/vercel/geist-font),
// Barlow (github.com/google/fonts ofl/barlow), IBM Plex Sans and Mono (github.com/IBM/plex),
// Kalam, a handwriting face for the sketch look (github.com/google/fonts ofl/kalam; Regular and Bold,
// the bold drawn at 600).
// For each: src/generated/font-<slug>.ts with the metrics and the woff2 to embed in SVGs.
// A family without a Reserved Font Name is embedded as a latin subset; IBM Plex reserves "Plex",
// so its files are embedded whole (woff2 is only a container) and never subsetted.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as fontkit from 'fontkit';
import wawoff2 from 'wawoff2';
import subsetFont from 'subset-font';

const require = createRequire(import.meta.url);
const inter = path.dirname(require.resolve('inter-ui/package.json'));
const theme = path.resolve(import.meta.dirname, '../packages/theme');
const weights = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold' };

fs.mkdirSync(path.join(theme, 'fonts'), { recursive: true });
fs.mkdirSync(path.join(theme, 'src/generated'), { recursive: true });
fs.copyFileSync(path.join(inter, 'LICENSE.txt'), path.join(theme, 'fonts/OFL-Inter.txt'));

const ranges = [[0x20, 0x7e], [0xa0, 0x24f], [0x2010, 0x2027], [0x2190, 0x21ff], [0x2022, 0x2022], [0x20ac, 0x20ac]];

/** Advance per code point and ASCII pair kerning, in font units. */
function weightMetrics(font) {
  const adv = {};
  for (const [a, b] of ranges)
    for (let cp = a; cp <= b; cp++) {
      if (!font.hasGlyphForCodePoint(cp)) continue;
      adv[cp] = font.glyphForCodePoint(cp).advanceWidth;
    }
  const kern = {};
  for (let a = 0x20; a <= 0x7e; a++)
    for (let b = 0x20; b <= 0x7e; b++) {
      const s = String.fromCodePoint(a, b);
      const run = font.layout(s);
      const k = run.positions[0].xAdvance - adv[a];
      if (k !== 0) kern[s] = k;
    }
  return { adv, kern, fallback: font.glyphForCodePoint(0x6e).advanceWidth };
}

const metrics = { family: 'Inter', weights: {} };
let embedded = '// Generated by scripts/fonts.mjs. Inter, SIL Open Font License 1.1 (fonts/OFL-Inter.txt).\n';
embedded += 'export const embeddedFonts: Record<number, string> = {\n';

for (const [weight, name] of Object.entries(weights)) {
  const ttf = Buffer.from(await wawoff2.decompress(fs.readFileSync(path.join(inter, `web/Inter-${name}.woff2`))));
  fs.writeFileSync(path.join(theme, `fonts/Inter-${name}.ttf`), ttf);
  const subset = fs.readFileSync(path.join(inter, `web-latin/Inter-${name}-subset.woff2`));
  embedded += `  ${weight}: '${subset.toString('base64')}',\n`;

  const font = fontkit.create(ttf);
  metrics.unitsPerEm ??= font.unitsPerEm;
  metrics.ascent ??= font.ascent;
  metrics.descent ??= font.descent;
  metrics.capHeight ??= font.capHeight;
  metrics.xHeight ??= font.xHeight;

  metrics.weights[weight] = weightMetrics(font);
}

embedded += '};\n';
fs.writeFileSync(path.join(theme, 'src/generated/fonts.ts'), embedded);
fs.writeFileSync(path.join(theme, 'src/generated/metrics.json'), JSON.stringify(metrics));
// ---- The families checked in as upstream TTF files.
const families = [
  { slug: 'instrument-sans', family: 'Instrument Sans', file: 'InstrumentSans', licence: 'OFL-InstrumentSans.txt', weights },
  { slug: 'geist-mono', family: 'Geist Mono', file: 'GeistMono', licence: 'OFL-GeistMono.txt', weights: { 400: 'Regular', 500: 'Medium' }, mono: true },
  { slug: 'barlow', family: 'Barlow', file: 'Barlow', licence: 'OFL-Barlow.txt', weights },
  { slug: 'ibm-plex-sans', family: 'IBM Plex Sans', file: 'IBMPlexSans', licence: 'OFL-IBMPlexSans.txt', weights, reserved: 'Plex' },
  { slug: 'kalam', family: 'Kalam', file: 'Kalam', licence: 'OFL-Kalam.txt', weights: { 400: 'Regular', 600: 'Bold' } },
  { slug: 'ibm-plex-mono', family: 'IBM Plex Mono', file: 'IBMPlexMono', licence: 'OFL-IBMPlexMono.txt', weights: { 400: 'Regular', 500: 'Medium' }, mono: true, reserved: 'Plex' },
];

for (const f of families) {
  const licence = fs.readFileSync(path.join(theme, 'fonts', f.licence), 'utf8');
  const declared = /with Reserved Font Name/i.test(licence.split('\n')[0]);
  if (declared !== !!f.reserved) throw new Error(`${f.family}: the licence ${declared ? 'declares' : 'does not declare'} a Reserved Font Name, the script says otherwise`);
  const out = { family: f.family, mono: !!f.mono, weights: {}, woff2: {} };
  for (const [weight, name] of Object.entries(f.weights)) {
    const ttf = fs.readFileSync(path.join(theme, `fonts/${f.file}-${name}.ttf`));
    const font = fontkit.create(ttf);
    out.unitsPerEm ??= font.unitsPerEm;
    out.capHeight ??= font.capHeight;
    out.weights[weight] = weightMetrics(font);
    // A reserved name forbids a modified version under that name: embed the file whole.
    const text = Object.keys(out.weights[weight].adv).map((cp) => String.fromCodePoint(Number(cp))).join('');
    const woff2 = f.reserved ? Buffer.from(await wawoff2.compress(ttf)) : await subsetFont(ttf, text, { targetFormat: 'woff2' });
    out.woff2[weight] = Buffer.from(woff2).toString('base64');
  }
  const note = f.reserved ? `whole files, Reserved Font Name "${f.reserved}"` : 'latin subset';
  const code = `// Generated by scripts/fonts.mjs. ${f.family}, SIL Open Font License 1.1 (fonts/${f.licence}); ${note}.\nimport type { BundledFont } from '../fonts.ts';\n\nexport const font: BundledFont = ${JSON.stringify(out)};\n`;
  fs.writeFileSync(path.join(theme, `src/generated/font-${f.slug}.ts`), code);
  console.log(f.family, Object.values(out.woff2).map((s) => Math.round((s.length * 3) / 4 / 1024) + ' kB').join(', '));
}
console.log('fonts written to', theme);
