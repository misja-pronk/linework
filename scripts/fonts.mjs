// Generates the font assets the theme package ships with, from the inter-ui package (OFL-1.1):
// - fonts/Inter-<Weight>.ttf        for PNG rendering with resvg (it cannot read woff2)
// - src/generated/fonts.ts           latin-subset woff2 as base64, embedded in exported SVGs
// - src/generated/metrics.json       glyph advances + ASCII kerning, so text is measured the
//                                    same in Node and the browser without loading a font parser
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as fontkit from 'fontkit';
import wawoff2 from 'wawoff2';

const require = createRequire(import.meta.url);
const inter = path.dirname(require.resolve('inter-ui/package.json'));
const theme = path.resolve(import.meta.dirname, '../packages/theme');
const weights = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold' };

fs.mkdirSync(path.join(theme, 'fonts'), { recursive: true });
fs.mkdirSync(path.join(theme, 'src/generated'), { recursive: true });
fs.copyFileSync(path.join(inter, 'LICENSE.txt'), path.join(theme, 'fonts/OFL-Inter.txt'));

const metrics = { family: 'Inter', weights: {} };
let embedded = '// Generated by scripts/fonts.mjs. Inter, SIL Open Font License 1.1 (fonts/OFL-Inter.txt).\n';
embedded += 'export const embeddedFonts: Record<number, string> = {\n';

for (const [weight, name] of Object.entries(weights)) {
  const ttf = Buffer.from(await wawoff2.decompress(fs.readFileSync(path.join(inter, `web/Inter-${name}.woff2`))));
  fs.writeFileSync(path.join(theme, `fonts/Inter-${name}.ttf`), ttf);
  const subset = fs.readFileSync(path.join(inter, `web-latin/Inter-${name}-subset.woff2`));
  embedded += `  ${weight}: '${subset.toString('base64')}',\n`;

  const font = fontkit.create(ttf);
  metrics.unitsPerEm ??= font.unitsPerEm;
  metrics.ascent ??= font.ascent;
  metrics.descent ??= font.descent;
  metrics.capHeight ??= font.capHeight;
  metrics.xHeight ??= font.xHeight;

  const adv = {};
  const ranges = [[0x20, 0x7e], [0xa0, 0x24f], [0x2010, 0x2027], [0x2190, 0x21ff], [0x2022, 0x2022], [0x20ac, 0x20ac]];
  for (const [a, b] of ranges)
    for (let cp = a; cp <= b; cp++) {
      if (!font.hasGlyphForCodePoint(cp)) continue;
      adv[cp] = font.glyphForCodePoint(cp).advanceWidth;
    }
  const kern = {};
  for (let a = 0x20; a <= 0x7e; a++)
    for (let b = 0x20; b <= 0x7e; b++) {
      const s = String.fromCodePoint(a, b);
      const run = font.layout(s);
      const k = run.positions[0].xAdvance - adv[a];
      if (k !== 0) kern[s] = k;
    }
  metrics.weights[weight] = { adv, kern, fallback: font.glyphForCodePoint(0x6e).advanceWidth };
}

embedded += '};\n';
fs.writeFileSync(path.join(theme, 'src/generated/fonts.ts'), embedded);
fs.writeFileSync(path.join(theme, 'src/generated/metrics.json'), JSON.stringify(metrics));
console.log('fonts written to', theme);
