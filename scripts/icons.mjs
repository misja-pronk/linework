// Builds the curated icon pack from lucide-static (ISC). Add a name here and run `pnpm icons`.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const names = `
  activity app-window archive arrow-left-right badge-check bell binary book-open bot boxes box braces
  brain briefcase building building-complex cable calendar chart-bar chart-line chart-pie check circle-dot clock cloud
  cloud-cog code cog container cpu credit-card database database-zap door-open earth ethernet-port eye file-box
  file-code file-braces file-spreadsheet file-text fingerprint-pattern flag folder folder-git-2 folder-key face-slightly-frowning gauge git-branch
  git-commit-horizontal git-fork git-merge git-pull-request globe handshake hard-drive hash heart id-card info key
  key-round key-square landmark laptop layers layout-grid link list-checks list-tree lock lock-keyhole mail map-pin face-neutral
  message-square monitor network orbit package phone play plug-zap radio-tower rocket router satellite-dish scale
  scroll-text search send server server-cog shield shield-check shield-user shopping-cart smartphone face-slightly-smiling face-grinning face-angry sparkles
  split square-dashed square-function square-stack star store table table-2 tag target terminal timer triangle-exclamation-point
  user user-cog user-round users variable waypoints webhook wifi workflow x zap
`.trim().split(/\s+/);

const require = createRequire(import.meta.url);
const lucide = path.dirname(require.resolve('lucide-static/package.json', { paths: [path.resolve(import.meta.dirname, '../packages/icons')] }));
const nodes = JSON.parse(fs.readFileSync(path.join(lucide, 'icon-nodes.json'), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
let out = '// Generated by scripts/icons.mjs from lucide-static (ISC licence, https://lucide.dev).\n';
out += '// Inner markup of 24×24 stroke icons.\nexport const lucide: Record<string, string> = {\n';
const missing = [];
for (const name of [...new Set(names)].sort()) {
  const node = nodes[name];
  if (!node) {
    missing.push(name);
    continue;
  }
  const markup = node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
  out += `  '${name}': '${markup}',\n`;
}
out += '};\n';
fs.mkdirSync(path.resolve(import.meta.dirname, '../packages/icons/src/generated'), { recursive: true });
fs.writeFileSync(path.resolve(import.meta.dirname, '../packages/icons/src/generated/lucide.ts'), out);
if (missing.length) console.warn('not in lucide:', missing.join(' '));
console.log(`${names.length - missing.length} icons written`);
